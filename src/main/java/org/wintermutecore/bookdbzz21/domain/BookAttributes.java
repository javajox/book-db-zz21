package org.wintermutecore.bookdbzz21.domain;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.Objects;
import java.util.Set;

/**
 * The book attributes an operator supplies, shared by {@link BookCreateInput} and
 * {@link BookUpdateInput}.
 *
 * <p>These values are <em>raw operator input</em>. Text is not yet normalized, ISBNs are not yet
 * stripped of hyphens, and keywords are not yet deduplicated; the validation and identity rules
 * perform that work and report field-specific errors. Consequently the structural checks here are
 * deliberately weak: an empty author set and a missing print length must both be representable so
 * they can be reported as field errors instead of crashing.
 *
 * <p>There is no {@code id} component. A book's identifier is generated by the system on creation
 * and is immutable afterwards, so no input type can set or change it.
 *
 * <p>Authors and the publisher are referenced by their internal identifiers, because a selection
 * must resolve to an existing record rather than silently creating one.
 *
 * <p>Note that {@code printLength} is a nullable {@link Integer} here while {@link Book#printLength()}
 * is a primitive {@code int}. An operator can leave the field blank, and a blank field must be
 * reported as missing rather than stored as zero.
 *
 * @param title raw title input
 * @param authorIds identifiers of the selected authors, as an unordered set
 * @param publicationDate optional publication date, or {@code null}
 * @param edition optional edition, or {@code null}
 * @param language raw language input
 * @param coverType optional cover type, or {@code null}
 * @param printLength page count, or {@code null} when the operator left it blank
 * @param isbn10 raw ISBN-10 input, possibly hyphenated, or {@code null}
 * @param isbn13 raw ISBN-13 input, possibly hyphenated, or {@code null}
 * @param weight optional weight in kilograms, or {@code null}
 * @param dimensions optional dimensions, or {@code null}
 * @param keywords raw comma-separated keywords, or {@code null}
 * @param publisherId identifier of the selected publisher, or {@code null} when none is selected
 */
public record BookAttributes(
        String title,
        Set<Long> authorIds,
        LocalDate publicationDate,
        Integer edition,
        String language,
        String coverType,
        Integer printLength,
        String isbn10,
        String isbn13,
        BigDecimal weight,
        String dimensions,
        String keywords,
        Long publisherId) {

    public BookAttributes {
        Objects.requireNonNull(authorIds, "authorIds");
        authorIds = Set.copyOf(authorIds);
    }

    /** A builder with every attribute unset. */
    public static Builder builder() {
        return new Builder();
    }

    /** A builder prefilled with these attributes, for deriving a variant of an existing input. */
    public Builder toBuilder() {
        return new Builder()
                .title(title)
                .authorIds(authorIds)
                .publicationDate(publicationDate)
                .edition(edition)
                .language(language)
                .coverType(coverType)
                .printLength(printLength)
                .isbn10(isbn10)
                .isbn13(isbn13)
                .weight(weight)
                .dimensions(dimensions)
                .keywords(keywords)
                .publisherId(publisherId);
    }

    /**
     * Assembles {@link BookAttributes} without requiring every optional attribute at a call site.
     *
     * <p>The book form has fifteen inputs and tests vary one at a time, so positional construction
     * would be unreadable and easy to get silently wrong.
     */
    public static final class Builder {

        private String title;
        private Set<Long> authorIds = Set.of();
        private LocalDate publicationDate;
        private Integer edition;
        private String language;
        private String coverType;
        private Integer printLength;
        private String isbn10;
        private String isbn13;
        private BigDecimal weight;
        private String dimensions;
        private String keywords;
        private Long publisherId;

        private Builder() {
        }

        public Builder title(String title) {
            this.title = title;
            return this;
        }

        public Builder authorIds(Set<Long> authorIds) {
            this.authorIds = authorIds == null ? Set.of() : Set.copyOf(authorIds);
            return this;
        }

        public Builder authorIds(Long... authorIds) {
            return authorIds(Set.of(authorIds));
        }

        public Builder publicationDate(LocalDate publicationDate) {
            this.publicationDate = publicationDate;
            return this;
        }

        public Builder edition(Integer edition) {
            this.edition = edition;
            return this;
        }

        public Builder language(String language) {
            this.language = language;
            return this;
        }

        public Builder coverType(String coverType) {
            this.coverType = coverType;
            return this;
        }

        public Builder printLength(Integer printLength) {
            this.printLength = printLength;
            return this;
        }

        public Builder isbn10(String isbn10) {
            this.isbn10 = isbn10;
            return this;
        }

        public Builder isbn13(String isbn13) {
            this.isbn13 = isbn13;
            return this;
        }

        public Builder weight(BigDecimal weight) {
            this.weight = weight;
            return this;
        }

        public Builder dimensions(String dimensions) {
            this.dimensions = dimensions;
            return this;
        }

        public Builder keywords(String keywords) {
            this.keywords = keywords;
            return this;
        }

        public Builder publisherId(Long publisherId) {
            this.publisherId = publisherId;
            return this;
        }

        public BookAttributes build() {
            return new BookAttributes(
                    title,
                    authorIds,
                    publicationDate,
                    edition,
                    language,
                    coverType,
                    printLength,
                    isbn10,
                    isbn13,
                    weight,
                    dimensions,
                    keywords,
                    publisherId);
        }

        /** Builds a creation input with no cover image. */
        public BookCreateInput buildCreateInput() {
            return new BookCreateInput(build(), null);
        }

        /** Builds a creation input carrying the supplied validated cover image. */
        public BookCreateInput buildCreateInput(CoverImage coverImage) {
            return new BookCreateInput(build(), coverImage);
        }

        /** Builds an update input that leaves the stored cover untouched. */
        public BookUpdateInput buildUpdateInput() {
            return new BookUpdateInput(build(), CoverImageAction.keep());
        }

        /** Builds an update input carrying the supplied cover action. */
        public BookUpdateInput buildUpdateInput(CoverImageAction coverImage) {
            return new BookUpdateInput(build(), coverImage);
        }
    }
}
